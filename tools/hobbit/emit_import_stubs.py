"""Write placeholder C definitions for every host import, and a name table.

Usage: emit_import_stubs.py <imports.h> <import_stubs.c>
Each imp_<name> calls recomp_missing_import("<name>"). The placeholders sit in
the __TEXT,__imp_ph section and are weak, so a real thunk in
runtime/src/thunk_*.c replaces one. Names that recon/import_sigs.json lists but
imports.h does not declare (data symbols, C++ runtime) also get a placeholder,
so the table below covers them.

The file also defines g_import_table (Mach-O name to imp_ function, in name
order) and import_func_is_placeholder(), which tells a placeholder from a real
thunk by its address: the linker drops the placeholders that a real thunk
replaced, and the survivors are the ones left inside the section.
"""
import json
import re
import sys
from pathlib import Path

DECL = re.compile(r"^extern\s+void\s+(imp_\w+)\s*\(\s*void\s*\)\s*;", re.M)
C_IDENT = re.compile(r"^[A-Za-z_]\w*$")
SIGS = Path(__file__).resolve().parents[2] / "recon" / "import_sigs.json"
SECTION = "__TEXT,__imp_ph,regular,pure_instructions"


def sig_names() -> dict[str, str]:
    """C-identifier form of each recon import name -> its Mach-O name."""
    if not SIGS.is_file():
        return {}
    imports = json.loads(SIGS.read_text(encoding="utf-8"))["imports"]
    return {i["name"].replace("$", "_"): i["name"] for i in imports}


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        declared: list[str] = DECL.findall(f.read())
    macho_of = sig_names()
    entries: dict[str, str] = {}  # imp_ symbol -> Mach-O name
    for sym in declared:
        entries[sym] = macho_of.get(sym[4:], sym[4:])
    for ident, macho in macho_of.items():
        if C_IDENT.match(ident) and "imp_" + ident not in entries:
            entries["imp_" + ident] = macho
    lines = [
        "/* Generated by tools/hobbit/emit_import_stubs.py. Do not edit. */",
        '#include "imports.h"',
        "",
        "extern void recomp_missing_import(const char *name);",
        "",
    ]
    for sym in entries:
        if sym not in declared:
            lines.append(f"extern void {sym}(void);")
    for sym in entries:
        # Weak, so a real thunk in runtime/src/thunk_*.c overrides it.
        lines.append(f'__attribute__((weak, section("{SECTION}"))) void {sym}(void) '
                     f'{{ recomp_missing_import("{sym[4:]}"); }}')
    lines += [
        "",
        "struct import_entry { const char *name; void (*fn)(void); };",
        "const struct import_entry g_import_table[] = {",
    ]
    for sym, macho in sorted(entries.items(), key=lambda kv: kv[1]):
        lines.append(f'    {{"{macho}", {sym}}},')
    lines += [
        "};",
        "const unsigned g_import_count = sizeof g_import_table / sizeof g_import_table[0];",
        "",
        'extern const char imp_ph_start[] __asm("section$start$__TEXT$__imp_ph");',
        'extern const char imp_ph_end[] __asm("section$end$__TEXT$__imp_ph");',
        "int import_func_is_placeholder(void (*fn)(void))",
        "{",
        "    const char *p = (const char *)fn;",
        "    return p >= imp_ph_start && p < imp_ph_end;",
        "}",
    ]
    with open(argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} import stubs to {argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
